export const messages: Record<Locale, Messages> = { ru, en, ka };

export type TranslationValues = Record<string, string | number>;

export function translate(
  locale: Locale,
  key: MessageKey,
  values: TranslationValues = {}
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key]
  );
}

export function formatProjectCount(locale: Locale, count: number): string {
  const pluralCategory = new Intl.PluralRules(locale).select(count);
  const key = `portfolio.project.${pluralCategory}` as MessageKey;
  const fallbackKey: MessageKey = "portfolio.project.other";
  const label = key in messages[locale] ? translate(locale, key) : translate(locale, fallbackKey);

  return `${count} ${label}`;
}
